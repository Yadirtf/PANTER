/**
 * Lee un stream hasta `maxBytes`. Si recibe un byte más, cancela el stream y devuelve null:
 * el límite vale aunque el Content-Length declarado mienta o falte (subida por chunks).
 * Sin cuerpo devuelve un arreglo vacío.
 */
export async function readLimited(
  body: ReadableStream<Uint8Array> | null,
  maxBytes: number,
): Promise<Uint8Array | null> {
  if (!body) return new Uint8Array(0);
  const reader = body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > maxBytes) {
      await reader.cancel('DOCUMENT_TOO_LARGE').catch(() => {});
      return null;
    }
    chunks.push(value);
  }
  const out = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return out;
}
